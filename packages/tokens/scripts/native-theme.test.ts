import { describe, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { dart, dartTheme, kotlin, kotlinTheme, load, ROOT, swift, swiftTheme, type Theme } from "./build";
import { toDtcg } from "./dtcg";

const { base, themes } = load();
const church = themes.find((t) => t.name === "church") as Theme;
const asApp = { ...church, name: "app" } as Theme;
const CLI = join(import.meta.dir, "cli.ts");
const run = (cwd: string, ...args: string[]) => Bun.spawnSync(["bun", CLI, ...args], { cwd });

/** The constructor call the SDK file uses for a theme, e.g. `DSThemeTokens(\n ... \n    )`. */
function constructorIn(file: string, marker: string): string {
  const start = file.indexOf(marker);
  expect(start).toBeGreaterThanOrEqual(0);
  const from = file.indexOf("DSThemeTokens(", start);
  let depth = 0;
  for (let i = from; i < file.length; i++) {
    if (file[i] === "(") depth++;
    if (file[i] === ")" && --depth === 0) return file.slice(from, i + 1).replace(/name: "church"|name = "church"|name: 'church'/, "NAME");
  }
  throw new Error("unbalanced");
}

describe("SDK types can be built outside the SDK", () => {
  test("every generated Swift struct has a public memberwise init", () => {
    const sdk = swift(base, themes);
    for (const name of ["DSShadowLayer", "DSTextRole", "DSColorScheme", "DSFontSizes", "DSLabelStyle", "DSMobileType", "DSThemeTokens"]) {
      const body = sdk.slice(sdk.indexOf(`public struct ${name}:`));
      expect(body.slice(0, body.indexOf("\n}\n"))).toContain("    public init(");
    }
    expect(sdk).toContain("public init(x: Double, y: Double, blur: Double, spread: Double, alpha: Double) {");
  });
});

describe("app-owned native themes", () => {
  test("Swift: an extension on DSTokens with the same constructor the SDK uses", () => {
    const out = swiftTheme(asApp, "design/theme.json");
    expect(out).toStartWith("// GENERATED by ds-tokens (@abrahamjeyaraj/tokens) from design/theme.json. Do not edit.");
    expect(out).toContain("import DesignSystem");
    expect(out).toContain("public extension DSTokens {");
    expect(out).toContain("    static let app = DSThemeTokens(");
    expect(constructorIn(out, "static let app").replace('name: "app"', "NAME")).toBe(constructorIn(swift(base, themes), "static let church"));
  });

  test("Kotlin: a top-level value in the app's package", () => {
    const out = kotlinTheme(asApp, "com.example.app.design", "design/theme.json");
    expect(out).toContain("package com.example.app.design");
    expect(out).toContain("import com.abrahamjeyaraj.designsystem.*");
    expect(out).toContain("val AppTheme: DSThemeTokens = DSThemeTokens(");
    expect(constructorIn(out, "val AppTheme").replace('name = "app"', "NAME")).toBe(constructorIn(kotlin(base, themes), "val church"));
  });

  test("Dart: a const theme next to the package import", () => {
    const out = dartTheme(asApp, "design/theme.json");
    expect(out).toContain("import 'package:design_system/design_system.dart';");
    expect(out).toContain("const appTheme = DSThemeTokens(");
    expect(constructorIn(out, "const appTheme").replace("name: 'app'", "NAME")).toBe(constructorIn(dart(base, themes), "static const church"));
  });

  test("CLI: swift, kotlin and dart targets with --check, from a DTCG theme", () => {
    const dir = mkdtempSync(join(tmpdir(), "ds-native-"));
    const src = JSON.parse(readFileSync(join(ROOT, "tokens/themes/church.json"), "utf8"));
    writeFileSync(join(dir, "theme.json"), JSON.stringify(toDtcg({ ...src, name: "app" })));
    expect(run(dir, "swift", "theme.json", "AppTheme.swift", "--check").exitCode).toBe(1);
    expect(run(dir, "swift", "theme.json", "AppTheme.swift").exitCode).toBe(0);
    expect(run(dir, "swift", "theme.json", "AppTheme.swift", "--check").exitCode).toBe(0);
    expect(run(dir, "kotlin", "theme.json", "AppTheme.kt", "--package", "com.example.app").exitCode).toBe(0);
    expect(readFileSync(join(dir, "AppTheme.kt"), "utf8")).toContain("package com.example.app");
    expect(run(dir, "dart", "theme.json", "app_theme.g.dart").exitCode).toBe(0);
    const noPackage = run(dir, "kotlin", "theme.json", "AppTheme.kt");
    expect(noPackage.exitCode).toBe(2);
  });
});
