import { describe, expect, test } from "bun:test";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ROOT } from "./build";
import { generate, generateCss } from "./cli";

const CLI = join(import.meta.dir, "cli.ts");
const theme = JSON.parse(readFileSync(join(ROOT, "tokens/themes/church.json"), "utf8"));

function workspace(src: object) {
  const dir = mkdtempSync(join(tmpdir(), "ds-tokens-"));
  writeFileSync(join(dir, "app.json"), JSON.stringify({ ...src, name: "app" }));
  return dir;
}
const run = (cwd: string, ...args: string[]) => Bun.spawnSync(["bun", CLI, ...args], { cwd });

describe("ds-tokens css", () => {
  test("a consumer theme gets the same CSS as a built-in theme, with its own header", () => {
    const dir = workspace({ ...theme, extra: { light: { "app-only": "#123456" }, dark: {} } });
    const css = generateCss("app.json", "out/theme.css", dir);
    expect(css).toStartWith("/* GENERATED by ds-tokens (@abrahamjeyaraj/tokens) from app.json. Do not edit. */");
    expect(css).toContain("--color-action:");
    expect(css).toContain("--color-app-only: #123456;");
    expect(css).toContain("@utility label-text");
  });

  test("writes, then --check passes until the theme changes", () => {
    const dir = workspace(theme);
    expect(run(dir, "css", "app.json", "theme.css", "--check").exitCode).toBe(1);
    expect(run(dir, "css", "app.json", "theme.css").exitCode).toBe(0);
    expect(run(dir, "css", "app.json", "theme.css", "--check").exitCode).toBe(0);
    writeFileSync(join(dir, "app.json"), JSON.stringify({ ...theme, name: "app", light: { ...theme.light, action: "#000000" } }));
    expect(run(dir, "css", "app.json", "theme.css", "--check").exitCode).toBe(1);
  });

  test("rejects a theme that breaks the role contract", () => {
    const { action: _, ...light } = theme.light;
    const dir = workspace({ ...theme, light });
    const result = run(dir, "css", "app.json", "theme.css");
    expect(result.exitCode).toBe(1);
    expect(result.stderr.toString()).toContain("missing roles [action]");
  });

  test("swift and kotlin targets write an app-owned native theme", () => {
    const dir = workspace(theme);
    expect(run(dir, "swift", "app.json", "Theme.swift").exitCode).toBe(0);
    const swift = readFileSync(join(dir, "Theme.swift"), "utf8");
    expect(swift).toContain("import DesignSystem");
    expect(swift).toContain("public static let app = DSThemeTokens(");
    expect(run(dir, "swift", "app.json", "Theme.swift", "--check").exitCode).toBe(0);

    expect(run(dir, "kotlin", "app.json", "Theme.kt").exitCode).toBe(2);
    expect(run(dir, "kotlin", "app.json", "Theme.kt", "--package", "com.example.ui").exitCode).toBe(0);
    const kotlin = readFileSync(join(dir, "Theme.kt"), "utf8");
    expect(kotlin).toContain("package com.example.ui");
    expect(kotlin).toContain("val AppTheme: DSThemeTokens = DSThemeTokens(");
    expect(run(dir, "kotlin", "app.json", "Theme.kt", "--check", "--package", "com.example.ui").exitCode).toBe(0);
  });

  test("platforms.tvos gives tvOS its own value; android overrides reach kotlin only", () => {
    const serif = { family: "Source Serif 4", fallback: ["serif"] };
    const dir = workspace({ ...theme, platforms: { tvos: { fontFamily: { heading: serif } }, android: { radius: { card: 4 } } } });
    const swift = generate("swift", "app.json", "Theme.swift", { cwd: dir });
    expect(swift).toContain("#if os(tvOS)");
    expect(swift.split("#else")[0]).toContain('"Source Serif 4"');
    expect(swift.split("#else")[1]).not.toContain('"Source Serif 4"');
    const kotlin = generate("kotlin", "app.json", "Theme.kt", { cwd: dir, pkg: "p" });
    expect(kotlin).toContain("card = 4.0");
    expect(generate("swift", "app.json", "T.swift", { cwd: workspace(theme) })).not.toContain("#if os(tvOS)");
  });

  test("rejects unknown platforms and non-overridable groups", () => {
    expect(() => generate("css", "app.json", "t.css", { cwd: workspace({ ...theme, platforms: { web: {} } }) })).toThrow("unknown platform");
    expect(() => generate("swift", "app.json", "t.swift", { cwd: workspace({ ...theme, platforms: { tvos: { light: {} } } }) })).toThrow("can be overridden");
  });

  test("bad arguments print usage", () => {
    expect(run(tmpdir(), "css").exitCode).toBe(2);
  });
});
