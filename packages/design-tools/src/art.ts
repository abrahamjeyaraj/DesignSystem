/**
 * ds-art: line-art scenes (onboarding, feature intros, empty states) as data. A scene is the
 * designer's paths with a draw window per stroke on a 0..1 timeline; platform players
 * (DSStrokeScene) render it, so no platform re-types coordinates.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { attr, inherited, readSvg, UnsupportedSvgError } from "./extract";
import { shapeToPath } from "./icons";

export const SCENE_SCHEMA = 1;
const HEADER = "GENERATED by ds-art from the app's art.json. Do not edit.";

type Point = [number, number];
type Window = [number, number];
export interface SceneStroke {
  d: string;
  width: number;
  window: Window;
  faint?: number;
  group?: string;
  fill?: boolean;
}
export interface SceneFly {
  from: Point;
  ctrl: Point;
  to: Point;
  radius: number;
  window: Window;
  group?: string;
}
export interface SceneKeyframe {
  t: number;
  rotate?: number;
  origin?: Point;
  translate?: Point;
  opacity?: number;
}
export interface Scene {
  schema: number;
  id: string;
  viewBox: [number, number, number, number];
  strokes: SceneStroke[];
  flies?: SceneFly[];
  groups?: Record<string, { keyframes: SceneKeyframe[] }>;
}

export function validateScene(s: Scene): string[] {
  const errors: string[] = [];
  if (s.schema !== SCENE_SCHEMA) errors.push(`schema ${s.schema} is not supported (expected ${SCENE_SCHEMA})`);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(s.id ?? "")) errors.push("id must be kebab-case");
  if (!Array.isArray(s.viewBox) || s.viewBox.length !== 4 || !(s.viewBox[2] > 0 && s.viewBox[3] > 0)) {
    errors.push("viewBox must be [minX, minY, width, height] with a positive size");
  }
  const groups = s.groups ?? {};
  const windowOk = (w: Window | undefined, path: string) => {
    if (!Array.isArray(w) || w.length !== 2 || w.some((x) => typeof x !== "number" || x < 0 || x > 1)) {
      errors.push(`${path}.window must be within 0..1`);
    } else if (w[0] > w[1]) {
      errors.push(`${path}.window: start ${w[0]} after end ${w[1]}`);
    }
  };
  const groupOk = (g: string | undefined, path: string) => {
    if (g !== undefined && !groups[g]) errors.push(`${path}.group "${g}" has no entry in groups`);
  };
  if (!s.strokes?.length) errors.push("strokes: at least one stroke");
  (s.strokes ?? []).forEach((k, i) => {
    const p = `strokes[${i}]`;
    if (typeof k.d !== "string" || !/^\s*[Mm]/.test(k.d)) errors.push(`${p}.d must start with M`);
    if (!(k.width > 0)) errors.push(`${p}.width must be > 0`);
    windowOk(k.window, p);
    if (k.faint !== undefined && !(k.faint >= 0 && k.faint <= 1)) errors.push(`${p}.faint must be between 0 and 1`);
    groupOk(k.group, p);
  });
  (s.flies ?? []).forEach((f, i) => {
    const p = `flies[${i}]`;
    if (!(f.radius > 0)) errors.push(`${p}.radius must be > 0`);
    windowOk(f.window, p);
    groupOk(f.group, p);
  });
  for (const [name, g] of Object.entries(groups)) {
    const ts = (g.keyframes ?? []).map((k) => k.t);
    if (ts.some((t) => !(t >= 0 && t <= 1))) errors.push(`groups.${name}.keyframes: t must be within 0..1`);
    if (ts.some((t, i) => i > 0 && t < ts[i - 1])) errors.push(`groups.${name}.keyframes must be in time order`);
  }
  return errors;
}

/** SVG opacity has no place in a scene; faintness is the scene's own, animatable, opacity. */
const SHAPE_OPACITY = ["opacity", "stroke-opacity", "fill-opacity"];

/**
 * Scene from an SVG the designer annotated: `data-window="start end"` on every shape, optional
 * `data-faint`, `data-group` on a parent <g>. Stroke width and fill are read the way SVG inherits
 * them: the shape's own (inline style first), else the nearest <g>'s, else the root's.
 * Transforms, clips, masks, references, text, bitmaps, opacity, even-odd fills and unstroked
 * shapes would be lost, so they are errors that say how to fix the source.
 */
export function extractScene(svg: string, id: string): Scene {
  let parsed: ReturnType<typeof readSvg>;
  try {
    parsed = readSvg(svg.trim());
  } catch (err) {
    if (err instanceof UnsupportedSvgError) throw new Error(`scene ${id}: ${err.message}`);
    throw err;
  }
  const { root, shapes } = parsed;
  for (const k of SHAPE_OPACITY) {
    if (attr(root, k)) throw new Error(`scene ${id}: <svg>: ${k} is not carried into the scene; use data-faint="0..1" on the strokes`);
  }
  const viewBox = (root.viewBox?.value ?? "").split(/[\s,]+/).map(Number) as Scene["viewBox"];
  const strokes = shapes.map((shape, i): SceneStroke => {
    const where = `<${shape.tag}> #${i + 1}`;
    const a = Object.fromEntries(Object.entries(shape.attrs).map(([k, v]) => [k, v.value]));
    for (const k of SHAPE_OPACITY) {
      if (attr(shape.attrs, k)) throw new Error(`scene ${id}: ${where}: ${k} is not carried into the scene; use data-faint="0..1" for a faint stroke`);
    }
    if (inherited(shape, "stroke")?.value === "none") {
      throw new Error(`scene ${id}: ${where}: stroke="none" cannot be drawn on; every scene shape is drawn as a stroke, so give it a stroke or leave it out of the scene`);
    }
    if (!a["data-window"]) throw new Error(`${where} has no data-window="start end"`);
    const window = a["data-window"].split(/[\s,]+/).map(Number) as Window;
    const stroke: SceneStroke = { d: shapeToPath(shape.tag, a), width: Number(inherited(shape, "stroke-width")?.value ?? 1), window };
    if (a["data-faint"] !== undefined) stroke.faint = Number(a["data-faint"]);
    const group = shape.ancestors
      .slice(1)
      .map((g) => g["data-group"]?.value)
      .filter(Boolean)
      .pop();
    if (group) stroke.group = group;
    const fill = inherited(shape, "fill")?.value;
    if (fill && fill !== "none") stroke.fill = true;
    return stroke;
  });
  return { schema: SCENE_SCHEMA, id, viewBox, strokes };
}

export interface ArtManifest {
  schema: number;
  scenes: string[];
  outputs?: { web?: string; json?: string };
}

export function buildArt(manifestPath: string, opts: { check?: boolean } = {}) {
  const dir = dirname(manifestPath);
  const m = JSON.parse(readFileSync(manifestPath, "utf8")) as ArtManifest;
  if (m.schema !== SCENE_SCHEMA) throw new Error(`${manifestPath}: schema ${m.schema} is not supported`);
  const scenes = m.scenes.map((file) => {
    const scene = JSON.parse(readFileSync(join(dir, file), "utf8")) as Scene;
    const errors = validateScene(scene);
    if (errors.length) throw new Error(`${file}:\n  ${errors.join("\n  ")}`);
    return scene;
  });
  const ids = scenes.map((s) => s.id);
  const dup = ids.find((id, i) => ids.indexOf(id) !== i);
  if (dup) throw new Error(`scene id "${dup}" is used twice`);

  const expected = new Map<string, string>();
  const o = m.outputs ?? {};
  if (o.web) {
    const body = scenes.map((s) => `  ${JSON.stringify(s.id)}: ${JSON.stringify(s, null, 2).replace(/\n/g, "\n  ")},`).join("\n");
    expected.set(
      join(dir, o.web),
      `// ${HEADER}\nexport type DSSceneId = ${ids.map((id) => JSON.stringify(id)).join(" | ") || "never"};\n\nexport const scenes = {\n${body}\n} as const;\n`,
    );
  }
  const jsonDir = o.json ? join(dir, o.json) : null;
  if (jsonDir) for (const s of scenes) expected.set(join(jsonDir, `${s.id}.json`), `${JSON.stringify(s, null, 2)}\n`);

  const extras = jsonDir && existsSync(jsonDir) ? readdirSync(jsonDir).filter((f) => f.endsWith(".json")).map((f) => join(jsonDir, f)).filter((f) => !expected.has(f)) : [];
  const changed = [...expected].filter(([p, c]) => !existsSync(p) || readFileSync(p, "utf8") !== c).map(([p]) => p);
  const rel = (p: string) => relative(dir, p);
  if (opts.check) return { scenes: ids, stale: [...changed, ...extras].map(rel), written: [] as string[] };
  for (const p of changed) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, expected.get(p) as string);
  }
  for (const p of extras) rmSync(p);
  return { scenes: ids, stale: [] as string[], written: changed.map(rel) };
}
