/**
 * ds-icons: one frozen icon set (custom SVGs or a pinned library), copied without change into
 * every platform's native vector format. Only icons the app's code uses are emitted, plus the
 * icons SDK components need. Geometry is never simplified or rounded.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { canonicalSvg, svgAttrs } from "./extract";

export const SCHEMA = 1;
/** Icons the SDK components render (disclosure, dismiss, search field, checkmarks, menus). */
export const COMPONENT_ICONS = ["chevron-right", "chevron-left", "chevron-down", "close", "check", "search", "add", "more"];
const LIBRARIES: Record<string, { pkg: string; dir: string }> = { lucide: { pkg: "lucide-static", dir: "icons" } };
const HEADER = "GENERATED by ds-icons from the app's icons.json. Do not edit.";

export interface Manifest {
  schema: number;
  source: { dir: string; library?: undefined; version?: undefined } | { library: string; version: string; dir?: undefined };
  style: { grid: number; stroke: number; linecap?: "round" | "butt" | "square"; linejoin?: "round" | "miter" | "bevel" };
  icons: Record<string, string>;
  scan?: string[];
  all?: boolean;
  outputs?: {
    web?: string;
    ios?: string;
    iosSwift?: string;
    android?: string;
    compose?: { file: string; package: string };
    flutter?: { dir: string; dart: string; assetPrefix?: string };
    sprite?: string;
  };
}

export interface Shape {
  tag: string;
  attrs: Record<string, string>;
  d: string;
  filled: boolean;
}
export interface IconDef {
  name: string;
  viewBox: string;
  grid: number;
  stroke: number;
  linecap: string;
  linejoin: string;
  filled: boolean;
  shapes: Shape[];
}

export function validateManifest(m: Manifest): string[] {
  const errors: string[] = [];
  if (m.schema !== SCHEMA) errors.push(`schema ${m.schema} is not supported (expected ${SCHEMA})`);
  const s = m.source ?? ({} as Manifest["source"]);
  if (Boolean(s.dir) === Boolean(s.library)) errors.push("source: exactly one of source.dir or source.library");
  if (s.library) {
    if (!LIBRARIES[s.library]) errors.push(`source.library "${s.library}" is not supported (supported: ${Object.keys(LIBRARIES)})`);
    if (!/^\d+\.\d+\.\d+$/.test(s.version ?? "")) errors.push(`source.version "${s.version}" must be an exact version (no latest, ^ or ~)`);
  }
  if (!(m.style?.grid > 0)) errors.push("style.grid must be > 0");
  if (!(m.style?.stroke > 0)) errors.push("style.stroke must be > 0");
  if (m.style?.linecap && !["round", "butt", "square"].includes(m.style.linecap)) errors.push("style.linecap must be round, butt or square");
  if (m.style?.linejoin && !["round", "miter", "bevel"].includes(m.style.linejoin)) errors.push("style.linejoin must be round, miter or bevel");
  if (!m.icons || !Object.keys(m.icons).length) errors.push("icons: at least one icon");
  for (const n of Object.keys(m.icons ?? {})) if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(n)) errors.push(`icons.${n}: names are kebab-case`);
  return errors;
}

// ---------- geometry ----------

const num = (v: string | undefined) => Number(v ?? 0);
const fmt = (n: number) => String(+n.toFixed(4));

/** Any SVG basic shape as path data, so VectorDrawable and ImageVector get the same geometry. */
export function shapeToPath(tag: string, a: Record<string, string>): string {
  switch (tag) {
    case "path":
      return a.d;
    case "circle":
    case "ellipse": {
      const [cx, cy] = [num(a.cx), num(a.cy)];
      const rx = tag === "circle" ? num(a.r) : num(a.rx);
      const ry = tag === "circle" ? num(a.r) : num(a.ry);
      return `M${fmt(cx - rx)} ${fmt(cy)}a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(2 * rx)} 0a${fmt(rx)} ${fmt(ry)} 0 1 0 ${fmt(-2 * rx)} 0`;
    }
    case "line":
      return `M${fmt(num(a.x1))} ${fmt(num(a.y1))}L${fmt(num(a.x2))} ${fmt(num(a.y2))}`;
    case "polyline":
    case "polygon": {
      const n = (a.points ?? "").trim().split(/[\s,]+/).map(Number);
      const pts: string[] = [];
      for (let i = 0; i + 1 < n.length; i += 2) pts.push(`${fmt(n[i])} ${fmt(n[i + 1])}`);
      return `M${pts.join("L")}${tag === "polygon" ? "Z" : ""}`;
    }
    case "rect": {
      const [x, y, w, h] = [num(a.x), num(a.y), num(a.width), num(a.height)];
      let rx = a.rx !== undefined ? num(a.rx) : a.ry !== undefined ? num(a.ry) : 0;
      let ry = a.ry !== undefined ? num(a.ry) : rx;
      rx = Math.min(rx, w / 2);
      ry = Math.min(ry, h / 2);
      if (!rx || !ry) return `M${fmt(x)} ${fmt(y)}H${fmt(x + w)}V${fmt(y + h)}H${fmt(x)}Z`;
      const arc = (ex: number, ey: number) => `A${fmt(rx)} ${fmt(ry)} 0 0 1 ${fmt(ex)} ${fmt(ey)}`;
      return [
        `M${fmt(x + rx)} ${fmt(y)}`,
        `H${fmt(x + w - rx)}`,
        arc(x + w, y + ry),
        `V${fmt(y + h - ry)}`,
        arc(x + w - rx, y + h),
        `H${fmt(x + rx)}`,
        arc(x, y + h - ry),
        `V${fmt(y + ry)}`,
        arc(x + rx, y),
        "Z",
      ].join("");
    }
    default:
      throw new Error(`<${tag}> is not a supported shape`);
  }
}

function parseIcon(name: string, raw: string, m: Manifest): IconDef {
  const canonical = canonicalSvg(raw);
  const viewBox = svgAttrs(canonical.match(/^<svg\b([^>]*)>/)?.[1] ?? "").viewBox?.value ?? "";
  const grid = m.style.grid;
  if (viewBox !== `0 0 ${grid} ${grid}`) throw new Error(`icons.${name}: viewBox "${viewBox}" is not the ${grid} grid`);
  if (/\btransform=/.test(canonical)) throw new Error(`icons.${name}: transforms are not supported; flatten the icon in the design tool`);
  const shapes = [...canonical.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*)\/>/g)].map((s) => {
    const all = Object.fromEntries(Object.entries(svgAttrs(s[2])).map(([k, v]) => [k, v.value]));
    const { fill, ...attrs } = all;
    return { tag: s[1], attrs, d: shapeToPath(s[1], attrs), filled: fill === "currentColor" };
  });
  if (!shapes.length) throw new Error(`icons.${name}: no shapes`);
  const filled = canonical.includes('<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + viewBox + '" fill="currentColor"');
  return {
    name,
    viewBox,
    grid,
    stroke: m.style.stroke,
    linecap: m.style.linecap ?? "round",
    linejoin: m.style.linejoin ?? "round",
    filled,
    shapes: shapes.map((s) => ({ ...s, filled: filled || s.filled })),
  };
}

function libraryRoot(lib: string, version: string, baseDir: string): string {
  const { pkg, dir } = LIBRARIES[lib];
  let pkgJson: string;
  try {
    pkgJson = createRequire(join(baseDir, "package.json")).resolve(`${pkg}/package.json`);
  } catch {
    try {
      pkgJson = createRequire(import.meta.url).resolve(`${pkg}/package.json`);
    } catch {
      throw new Error(`source.library ${lib}: install ${pkg}@${version} (exact) in the app`);
    }
  }
  const installed = JSON.parse(readFileSync(pkgJson, "utf8")).version;
  if (installed !== version) throw new Error(`source.library: pinned ${lib} ${version} but ${installed} is installed (${pkg})`);
  return join(dirname(pkgJson), dir);
}

export function loadIcons(manifestPath: string): { manifest: Manifest; icons: IconDef[]; dir: string } {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as Manifest;
  const errors = validateManifest(manifest);
  if (errors.length) throw new Error(`${manifestPath}:\n  ${errors.join("\n  ")}`);
  const dir = dirname(manifestPath);
  const src = manifest.source;
  const root = src.library ? libraryRoot(src.library, src.version, dir) : join(dir, src.dir as string);
  const icons = Object.entries(manifest.icons)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, file]) => {
      const path = join(root, `${file}.svg`);
      if (!existsSync(path)) {
        throw new Error(src.library ? `icons.${name}: ${src.library} has no icon "${file}"` : `icons.${name}: ${src.dir}/${file}.svg not found`);
      }
      return parseIcon(name, readFileSync(path, "utf8"), manifest);
    });
  return { manifest, icons, dir };
}

// ---------- names ----------

const camel = (n: string) => n.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const pascal = (n: string) => camel(n).replace(/^./, (c) => c.toUpperCase());
const SWIFT_RESERVED = new Set(["default", "repeat", "return", "import", "switch", "case", "class", "func", "let", "var", "in", "is", "as", "for", "if", "else", "while", "do", "try", "throw", "where", "self", "super", "init", "nil", "true", "false", "enum", "struct", "protocol", "extension", "public", "private", "static", "operator"]);
const DART_RESERVED = new Set(["default", "switch", "case", "class", "return", "import", "if", "else", "for", "while", "do", "try", "throw", "new", "null", "true", "false", "this", "super", "var", "final", "const", "in", "is", "enum", "extends", "with"]);
const swiftCase = (n: string) => {
  const id = /^\d/.test(n) ? `icon${pascal(n)}` : camel(n);
  return SWIFT_RESERVED.has(id) ? `\`${id}\`` : id;
};
const dartName = (n: string) => {
  const id = /^\d/.test(n) ? `icon${pascal(n)}` : camel(n);
  return DART_RESERVED.has(id) ? `${id}Icon` : id;
};
const ktName = (n: string) => (/^\d/.test(n) ? `Icon${pascal(n)}` : pascal(n));
const resName = (n: string) => `ds_ic_${n.replace(/-/g, "_")}`;
const assetName = (n: string) => `ds-icon-${n}`;

// ---------- usage ----------

const CODE = /\.(tsx?|jsx?|swift|kt|dart)$/;
function codeFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    if (name.startsWith(".") || name === "node_modules" || name === "build") continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...codeFiles(full));
    else if (CODE.test(name)) out.push(full);
  }
  return out;
}

/** Icon names the app's code references through the DSIcon APIs of each platform. */
export function scanUsage(dirs: string[], names: string[]): { used: string[]; missing: string[] } {
  const byIdent = new Map<string, string>();
  for (const n of names) for (const id of [n, camel(n), pascal(n), swiftCase(n).replace(/`/g, ""), dartName(n), ktName(n)]) byIdent.set(id, n);
  const kebab = (id: string) => byIdent.get(id) ?? id.replace(/^[A-Z]/, (c) => c.toLowerCase()).replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
  const used = new Set<string>();
  const missing = new Set<string>();
  const note = (id: string) => {
    const n = kebab(id);
    (names.includes(n) ? used : missing).add(n);
  };
  for (const file of dirs.flatMap(codeFiles)) {
    const text = readFileSync(file, "utf8");
    for (const m of text.matchAll(/<DSIcon\b[^>]*?\bname=\{?["']([a-z0-9-]+)["']/g)) note(m[1]);
    for (const m of text.matchAll(/DSIcon\(\s*\.([A-Za-z0-9_]+)/g)) note(m[1]);
    for (const m of text.matchAll(/DSIconName\.([A-Za-z0-9_]+)/g)) if (m[1] !== "allCases") note(m[1]);
    for (const m of text.matchAll(/DSIcons\.([A-Za-z0-9_]+)/g)) if (m[1] !== "all") note(m[1]);
  }
  return { used: [...used].sort(), missing: [...missing].sort() };
}

// ---------- emitters ----------

const attrList = (a: Record<string, string>) => Object.entries(a).map(([k, v]) => `${k}="${v}"`).join(" ");

/** Standalone SVG with explicit colour, for asset catalogs and Flutter. */
function assetSvg(icon: IconDef, color = "#000000"): string {
  const root = icon.filled
    ? `fill="${color}"`
    : `fill="none" stroke="${color}" stroke-width="${icon.stroke}" stroke-linecap="${icon.linecap}" stroke-linejoin="${icon.linejoin}"`;
  const body = icon.shapes.map((s) => `<${s.tag} ${attrList(s.attrs)}${s.filled && !icon.filled ? ` fill="${color}"` : ""}/>`).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${icon.grid}" height="${icon.grid}" viewBox="${icon.viewBox}" ${root}>${body}</svg>\n`;
}

export function emitWeb(icons: IconDef[]): string {
  const names = icons.map((i) => JSON.stringify(i.name));
  const entry = (i: IconDef) => {
    const shapes = i.shapes
      .map((s) => `[${JSON.stringify(s.tag)}, { ${Object.entries(s.attrs).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(", ")} }, ${s.filled}]`)
      .join(", ");
    return `  ${JSON.stringify(i.name)}: { viewBox: ${JSON.stringify(i.viewBox)}, stroke: ${i.stroke}, filled: ${i.filled}, shapes: [${shapes}] },`;
  };
  return `// ${HEADER}
export type DSIconName = ${names.join(" | ") || "never"};
export type DSIconShape = [tag: string, attrs: Record<string, string>, filled: boolean];
export interface DSIconData {
  viewBox: string;
  stroke: number;
  filled: boolean;
  shapes: DSIconShape[];
}

export const iconStyle = { linecap: ${JSON.stringify(icons[0]?.linecap ?? "round")}, linejoin: ${JSON.stringify(icons[0]?.linejoin ?? "round")} } as const;

export const icons: Record<DSIconName, DSIconData> = {
${icons.map(entry).join("\n")}
};
`;
}

export function emitIos(icons: IconDef[]): Record<string, string> {
  const info = { author: "ds-icons", version: 1 };
  const files: Record<string, string> = { "Contents.json": `${JSON.stringify({ info }, null, 2)}\n` };
  for (const i of icons) {
    const a = assetName(i.name);
    files[`${a}.imageset/Contents.json`] = `${JSON.stringify(
      {
        images: [{ filename: `${a}.svg`, idiom: "universal" }],
        info,
        properties: { "preserves-vector-representation": true, "template-rendering-intent": "template" },
      },
      null,
      2,
    )}\n`;
    files[`${a}.imageset/${a}.svg`] = assetSvg(i);
  }
  return files;
}

export function emitIosSwift(icons: IconDef[]): string {
  return `// ${HEADER}
import SwiftUI

/// The app's icons, from its asset catalog, as template images tinted by the foreground style.
public enum DSIconName: String, CaseIterable {
${icons.map((i) => `    case ${swiftCase(i.name)} = "${assetName(i.name)}"`).join("\n")}

    public var image: Image { Image(rawValue).renderingMode(.template) }
}
`;
}

export function emitAndroid(icons: IconDef[]): Record<string, string> {
  const files: Record<string, string> = {};
  for (const i of icons) {
    const paths = i.shapes.map((s) => {
      const lines = [`        android:pathData="${s.d}"`];
      if (s.filled) lines.push('        android:fillColor="#FF000000"');
      if (!i.filled) {
        lines.push(
          '        android:strokeColor="#FF000000"',
          `        android:strokeWidth="${i.stroke}"`,
          `        android:strokeLineCap="${i.linecap}"`,
          `        android:strokeLineJoin="${i.linejoin}"`,
        );
      }
      if (s.attrs.opacity) lines.push(`        android:fillAlpha="${s.attrs.opacity}"`, `        android:strokeAlpha="${s.attrs.opacity}"`);
      return `    <path\n${lines.join("\n")} />`;
    });
    files[`${resName(i.name)}.xml`] = `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${i.grid}dp"
    android:height="${i.grid}dp"
    android:viewportWidth="${i.grid}"
    android:viewportHeight="${i.grid}">
${paths.join("\n")}
</vector>
`;
  }
  return files;
}

export function emitCompose(icons: IconDef[], pkg: string): string {
  const stroke = icons[0]?.stroke ?? 1;
  const grid = icons[0]?.grid ?? 24;
  const cap = { round: "Round", butt: "Butt", square: "Square" }[icons[0]?.linecap ?? "round"];
  const join = { round: "Round", miter: "Miter", bevel: "Bevel" }[icons[0]?.linejoin ?? "round"];
  const esc = (s: string) => s.replace(/\$/g, "\\$");
  const shape = (s: Shape) => {
    const alpha = s.attrs.opacity ? `, alpha = ${Number(s.attrs.opacity)}f` : "";
    return `S("${esc(s.d)}"${s.filled ? ", filled = true" : ""}${alpha})`;
  };
  return `// ${HEADER}
package ${pkg}

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

private const val STROKE = ${stroke}f
private const val GRID = ${grid}f

/** The app's icons as ImageVectors, drawn in black; tint with Icon(tint = ...). */
object DSIcons {
${icons.map((i) => `    val ${ktName(i.name)}: ImageVector by lazy { icon("${i.name}", ${!i.filled}, ${i.shapes.map(shape).join(", ")}) }`).join("\n")}

    val all: Map<String, ImageVector> by lazy {
        mapOf(
${icons.map((i) => `            "${i.name}" to ${ktName(i.name)},`).join("\n")}
        )
    }
}

private data class S(val d: String, val filled: Boolean = false, val alpha: Float = 1f)

private fun icon(name: String, stroked: Boolean, vararg shapes: S): ImageVector =
    ImageVector.Builder(name = name, defaultWidth = GRID.dp, defaultHeight = GRID.dp, viewportWidth = GRID, viewportHeight = GRID)
        .apply {
            for (s in shapes) {
                addPath(
                    pathData = addPathNodes(s.d),
                    fill = if (s.filled) SolidColor(Color.Black) else null,
                    fillAlpha = s.alpha,
                    stroke = if (stroked) SolidColor(Color.Black) else null,
                    strokeAlpha = s.alpha,
                    strokeLineWidth = if (stroked) STROKE else 0f,
                    strokeLineCap = StrokeCap.${cap},
                    strokeLineJoin = StrokeJoin.${join},
                )
            }
        }
        .build()
`;
}

export function emitFlutter(icons: IconDef[], assetPrefix: string): { assets: Record<string, string>; dart: string } {
  const assets = Object.fromEntries(icons.map((i) => [`${i.name}.svg`, assetSvg(i)]));
  const dart = `// ${HEADER}
/// Asset paths of the app's icons. Render with flutter_svg and tint with the theme colour.
abstract final class DSIcons {
${icons.map((i) => `  static const String ${dartName(i.name)} = '${assetPrefix}/${i.name}.svg';`).join("\n")}

  static const Map<String, String> all = {
${icons.map((i) => `    '${i.name}': ${dartName(i.name)},`).join("\n")}
  };
}
`;
  return { assets, dart };
}

export function emitSprite(icons: IconDef[]): string {
  const symbols = icons.map((i) => {
    const root = i.filled
      ? 'fill="currentColor"'
      : `fill="none" stroke="currentColor" stroke-width="${i.stroke}" stroke-linecap="${i.linecap}" stroke-linejoin="${i.linejoin}"`;
    const body = i.shapes.map((s) => `<${s.tag} ${attrList(s.attrs)}${s.filled && !i.filled ? ' fill="currentColor"' : ""}/>`).join("");
    return `  <symbol id="${i.name}" viewBox="${i.viewBox}" ${root}>${body}</symbol>`;
  });
  return `<!-- ${HEADER} -->\n<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols.join("\n")}\n</svg>\n`;
}

// ---------- build ----------

export interface BuildResult {
  icons: string[];
  warnings: string[];
  stale: string[];
  written: string[];
}

/** The icons an app ships: those its code uses plus the component icons, or all with `all`. */
export function selectIcons(manifestPath: string, opts: { all?: boolean } = {}) {
  const loaded = loadIcons(manifestPath);
  const { manifest, icons, dir } = loaded;
  const names = icons.map((i) => i.name);
  const { used, missing } = scanUsage((manifest.scan ?? []).map((d) => join(dir, d)), names);
  if (missing.length) throw new Error(`used but not in icons.json: ${missing.join(", ")}`);
  const everything = opts.all || manifest.all;
  const selected = icons.filter((i) => everything || used.includes(i.name) || COMPONENT_ICONS.includes(i.name));
  return { ...loaded, names, selected };
}

/** Where a library or custom set keeps the source SVG for an icon. */
export function sourcePath(manifest: Manifest, dir: string, file: string): string {
  const src = manifest.source;
  const root = src.library ? libraryRoot(src.library, src.version, dir) : join(dir, src.dir as string);
  return join(root, `${file}.svg`);
}

export const iconFileNames = { asset: assetName, res: resName, kotlin: ktName };

export function buildIcons(manifestPath: string, opts: { check?: boolean; all?: boolean } = {}): BuildResult {
  const { manifest, dir, names, selected } = selectIcons(manifestPath, opts);
  const warnings: string[] = [];
  const unused = names.filter((n) => !selected.some((i) => i.name === n));
  if (unused.length) warnings.push(`unused: ${unused.join(", ")}`);
  const absentComponents = COMPONENT_ICONS.filter((n) => !names.includes(n));
  if (absentComponents.length) warnings.push(`component icons not in the set (SDK components fall back to none): ${absentComponents.join(", ")}`);

  const expected = new Map<string, string>();
  const owned: { dir: string; match: (f: string) => boolean }[] = [];
  const o = manifest.outputs ?? {};
  const put = (base: string, files: Record<string, string>) => {
    for (const [f, c] of Object.entries(files)) expected.set(join(dir, base, f), c);
  };
  if (o.web) expected.set(join(dir, o.web), emitWeb(selected));
  if (o.ios) {
    put(o.ios, emitIos(selected));
    owned.push({ dir: join(dir, o.ios), match: () => true });
  }
  if (o.iosSwift) expected.set(join(dir, o.iosSwift), emitIosSwift(selected));
  if (o.android) {
    put(o.android, emitAndroid(selected));
    owned.push({ dir: join(dir, o.android), match: (f) => /^ds_ic_.*\.xml$/.test(f.split("/").pop() ?? "") });
  }
  if (o.compose) expected.set(join(dir, o.compose.file), emitCompose(selected, o.compose.package));
  if (o.flutter) {
    const f = emitFlutter(selected, o.flutter.assetPrefix ?? "assets/ds_icons");
    put(o.flutter.dir, f.assets);
    expected.set(join(dir, o.flutter.dart), f.dart);
    owned.push({ dir: join(dir, o.flutter.dir), match: (p) => p.endsWith(".svg") });
  }
  if (o.sprite) expected.set(join(dir, o.sprite), emitSprite(selected));

  const extras: string[] = [];
  const list = (d: string): string[] =>
    existsSync(d) ? readdirSync(d).flatMap((n) => (statSync(join(d, n)).isDirectory() ? list(join(d, n)) : [join(d, n)])) : [];
  for (const { dir: d, match } of owned) for (const f of list(d)) if (match(relative(d, f)) && !expected.has(f)) extras.push(f);

  const changed = [...expected].filter(([p, c]) => !existsSync(p) || readFileSync(p, "utf8") !== c).map(([p]) => p);
  const rel = (p: string) => relative(dir, p);
  if (opts.check) return { icons: selected.map((i) => i.name), warnings, stale: [...changed, ...extras].map(rel), written: [] };

  for (const p of changed) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, expected.get(p) as string);
  }
  for (const p of extras) rmSync(p);
  for (const { dir: d } of owned) {
    for (const sub of existsSync(d) ? readdirSync(d) : []) {
      const full = join(d, sub);
      if (statSync(full).isDirectory() && !readdirSync(full).length) rmSync(full, { recursive: true });
    }
  }
  return { icons: selected.map((i) => i.name), warnings, stale: [], written: changed.map(rel) };
}
